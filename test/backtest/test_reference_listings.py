def _windows():
    for line in LISTED.splitlines():
        trade, exchange, *entries = line.split()
        for entry in entries:
            underlying, _, dates = entry.partition(":")
            yield trade, exchange, underlying, [item for item in dates.split(",") if item]


WINDOWS = list(_windows())
CONTRACTS = [
    (trade, exchange, underlying, *item.partition(">")[::2])
    for trade, exchange, underlying, items in WINDOWS
    for item in items
]


@pytest.fixture(scope="module")
def tables():
    return ReferenceTables()


@pytest.fixture(scope="module")
def calendar():
    return default_calendar()


def _day(text):
    return dt.date.fromisoformat(text)


@pytest.mark.parametrize("trade,exchange,underlying,listed", WINDOWS)
def test_contracts_given_for_the_next_13_days_are_the_listed_ones(
    tables, calendar, trade, exchange, underlying, listed
):
    first = _day(trade)
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", ReferenceDataWarning)
        schedule = tables.expiry_schedule(
            underlying, exchange, first, first + WINDOW, calendar, as_of=first
        )
    given = [item.expiry.isoformat() for item in schedule]
    shown = [item.partition(">")[0] for item in listed]
    if exchange == "NFO":
        assert given == shown
    else:
        assert set(shown) <= set(given)
        assert set(given) - set(shown) <= set(NOTICE_LISTED.get((trade, underlying), []))


@pytest.mark.parametrize("trade,exchange,underlying,expiry,actual", CONTRACTS)
def test_listed_contract_resolves_with_its_listed_expiry_and_last_trading_day(
    tables, calendar, trade, exchange, underlying, expiry, actual
):
    symbol = format_symbol(underlying, _day(expiry))
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", ReferenceDataWarning)
        future = tables.instrument(
            symbol, exchange, trade, calendar=calendar, allow_missing=("freeze_qty", "tick_size")
        )
    assert (future.symbol, future.expiry) == (symbol, _day(expiry))
    assert future.last_trading_day == _day(actual or expiry)
